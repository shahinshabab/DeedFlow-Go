"""Generates the Go data files that must match the Django project byte for
byte (Malayalam strings, ordered maps) by importing the Python modules.

    python tools/gen/gen_data.py /path/to/DeedFlow/backend
"""
import json, os, sys

backend = sys.argv[1]
sys.path.insert(0, backend)
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
from django.conf import settings
settings.configure(OPENAI_API_KEY="", OPENAI_MODEL="", ANTHROPIC_API_KEY="", ANTHROPIC_MODEL="x", AI_CLAUDE_FALLBACK=False,
                   TESSERACT_CMD="tesseract", INSTALLED_APPS=[])

def q(s):
    return json.dumps(s, ensure_ascii=False)

def pairs(items, indent="\t"):
    return "".join(f"{indent}{{{q(a)}, {q(b)}}},\n" for a, b in items)

# ---- text conversion maps ------------------------------------------------
from deeds.utils.text_conversion import TextConverter
tc = TextConverter()
out = ["// Code generated by tools/gen/gen_data.py from deeds/utils/text_conversion.py; DO NOT EDIT.\n",
       "package textconv\n\n",
       "// Pair is an ordered key/value entry.\ntype Pair struct{ Key, Value string }\n\n",
       "// FontMap maps the legacy font's glyph codes to Unicode (in the Python dict's order).\nvar FontMap = []Pair{\n"]
out.append(pairs(tc.font_map.items()).replace("{", "{", 1))
out.append("}\n\n// NormalizerMap are the clean-up replacements applied in order after substitution.\nvar NormalizerMap = []Pair{\n")
out.append(pairs(tc.normalizer_map.items()))
out.append("}\n\n")
out.append("var preBaseSigns = []string{" + ", ".join(q(x) for x in tc.preBase) + "}\n")
out.append("var postBaseSigns = []string{" + ", ".join(q(x) for x in tc.postBase) + "}\n")
open("internal/textconv/maps_gen.go", "w").write("".join(out))

# ---- choices -------------------------------------------------------------
from deeds import choices as ch
from deeds.kerala_data import KERALA_DISTRICTS
from deeds.utils import registration_reference as rr
def goPairs(name, seq, doc):
    return f"// {doc}\nvar {name} = []Choice{{\n" + "".join(f"\t{{{q(str(v))}, {q(l)}}},\n" for v, l in seq) + "}\n\n"

o = ["// Code generated by tools/gen/gen_data.py from deeds/choices.py, kerala_data.py and registration_reference.py; DO NOT EDIT.\n",
     "package deeds\n\n"]
o.append(goPairs("GenderChoices", ch.GENDER_CHOICES, "GenderChoices are the gender options."))
o.append(goPairs("RelationChoices", ch.RELATION_CHOICES, "RelationChoices are the relation options (the portal's own spelling)."))
o.append(goPairs("IDTypeChoices", ch.ID_TYPE_CHOICES, "IDTypeChoices are the ID card types."))
o.append(goPairs("PriorDocumentTypeChoices", ch.PRIOR_DOCUMENT_TYPE_CHOICES, "PriorDocumentTypeChoices are the prior document types."))
o.append("// PriorDocTypeValues maps a prior document type to the portal's option value.\nvar PriorDocTypeValues = map[string]string{\n"
         + "".join(f"\t{q(k)}: {q(v)},\n" for k, v in ch.PRIOR_DOC_TYPE_VALUES.items()) + "}\n\n")
o.append("// PriorDocumentTypeMeanings explains each prior document type to the AI step.\nvar PriorDocumentTypeMeanings = map[string]string{\n"
         + "".join(f"\t{q(k)}: {q(v)},\n" for k, v in ch.PRIOR_DOCUMENT_TYPE_MEANINGS.items()) + "}\n\n")
o.append(goPairs("BookChoices", ch.BOOK_CHOICES, "BookChoices are the registration books."))
o.append(goPairs("PartyCapacityChoices", ch.PARTY_CAPACITY_CHOICES, "PartyCapacityChoices are the capacities of a presenter, executant or claimant."))
o.append(goPairs("StampModeChoices", ch.STAMP_MODE_CHOICES, "StampModeChoices are the stamp modes."))
o.append(goPairs("WitnessTypeChoices", ch.WITNESS_TYPE_CHOICES, "WitnessTypeChoices pick the witness page."))
o.append(goPairs("WitnessPortalTypeChoices", ch.WITNESS_PORTAL_TYPE_CHOICES, "WitnessPortalTypeChoices are the portal's own witness types."))
o.append(goPairs("YesNoChoices", ch.YES_NO_CHOICES, "YesNoChoices are Yes/No."))

o.append("// KeralaDistrict is a district with its SROs and taluks.\ntype KeralaDistrict struct {\n\tName   string\n\tSROs   []string\n\tTaluks []string\n}\n\n")
o.append("// KeralaDistricts is the curated district/SRO/taluk list, in order.\nvar KeralaDistricts = []KeralaDistrict{\n")
for d, info in KERALA_DISTRICTS.items():
    o.append(f"\t{{{q(d)}, []string{{" + ", ".join(q(s) for s in info["sros"]) + "}, []string{" + ", ".join(q(t) for t in info["taluks"]) + "}},\n")
o.append("}\n\n")

o.append("// DeedTypeMapping is the portal labels for one deed type.\ntype DeedTypeMapping struct {\n\tName             string\n\tBook             int\n\tRegistrationType string\n\tSubType          string\n}\n\n")
o.append("// DeedTypePortalMapping lists the deed types in the Python dict's order.\nvar DeedTypePortalMapping = []DeedTypeMapping{\n")
for k, v in rr.DEED_TYPE_PORTAL_MAPPING.items():
    o.append(f"\t{{{q(k)}, {v['book']}, {q(v['registration_type'])}, {q(v['registration_sub_type'])}}},\n")
o.append("}\n\n")
o.append(f"// DefaultDeedType is used when a deed type isn't known.\nconst DefaultDeedType = {q(rr.DEFAULT_DEED_TYPE)}\n\n")
o.append("// BookPortalLabels are the portal's labels of the books.\nvar BookPortalLabels = map[int]string{\n" + "".join(f"\t{k}: {q(v)},\n" for k, v in rr.BOOK_PORTAL_LABELS.items()) + "}\n")
open("internal/deeds/data_gen.go", "w").write("".join(o))

