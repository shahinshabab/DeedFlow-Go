"""Dumps indic_transliteration's Malayalam -> ITRANS scheme map as Go data."""
import json
import sys

from indic_transliteration import sanscript

m = sanscript._get_scheme_map(sanscript.MALAYALAM, sanscript.ITRANS)
fs, ts = m.from_scheme, m.to_scheme
data = {
    "vowel_marks": m.vowel_marks,
    "virama": m.virama,
    "consonants": m.consonants,
    "non_marks_viraama": m.non_marks_viraama,
    "accents": m.accents,
    "max_key": m.max_key_length_from_scheme,
    "from_shortcuts": dict(fs.get("shortcuts", {})),
    "to_shortcuts": dict(ts.get("shortcuts", {})),
    "yogavaahas": "".join(fs["yogavaahas"]) if "yogavaahas" in fs else "",
    "to_is_roman": bool(ts.is_roman),
}
out = sys.argv[1]
def q(s):
    return json.dumps(s, ensure_ascii=False)
def gomap(name, d):
    keys = sorted(d)
    return "var %s = map[string]string{\n%s}\n" % (name, "".join("\t%s: %s,\n" % (q(k), q(d[k])) for k in keys))
with open(out, "w", encoding="utf-8") as f:
    f.write("// Code generated by tools/gen/gen_translit.py; DO NOT EDIT.\n\npackage translit\n\n")
    for n in ("vowel_marks", "virama", "consonants", "non_marks_viraama", "accents"):
        f.write(gomap("m_" + n, data[n]))
    f.write("\nconst maxKey = %d\n" % data["max_key"])
    f.write("const yogavaahas = %s\n" % q(data["yogavaahas"]))
    f.write("var fromShortcuts = [][2]string{%s}\n" % "".join("{%s, %s}, " % (q(k), q(v)) for k, v in data["from_shortcuts"].items()))
    f.write("var toShortcuts = [][2]string{%s}\n" % "".join("{%s, %s}, " % (q(k), q(v)) for k, v in data["to_shortcuts"].items()))
    f.write("const toIsRoman = %s\n" % ("true" if data["to_is_roman"] else "false"))
print({k: len(v) if hasattr(v, '__len__') else v for k, v in data.items()})
