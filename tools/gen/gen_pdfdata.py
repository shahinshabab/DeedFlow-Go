"""Generates internal/plumber/encdata_gen.go from pdfminer: the standard text
encodings, Adobe's glyph list, and the standard-14 font metrics - the data
pdfplumber's character extraction depends on."""
import json, sys
from pdfminer.encodingdb import EncodingDB
from pdfminer.glyphlist import glyphname2unicode
from pdfminer.fontmetrics import FONT_METRICS

import unicodedata
def q(s):
    out = json.dumps(s, ensure_ascii=False)
    # keep format / separator / private-use characters visible and legal in Go source
    return "".join(c if unicodedata.category(c) not in ("Cf", "Zl", "Zp", "Co", "Cs") else "\\u%04x" % ord(c) if ord(c) < 0x10000 else "\\U%08x" % ord(c) for c in out)

out = ["// Code generated by tools/gen/gen_pdfdata.py from pdfminer; DO NOT EDIT.\n\npackage plumber\n\n"]
out.append("// stdEncodings holds, per PDF encoding name, the text of each of the 256 codes (\"\" when undefined).\n")
out.append("var stdEncodings = map[string]*[256]string{\n")
for name, table in EncodingDB.encodings.items():
    out.append(f"\t{q(name)}: {{\n")
    for code in range(256):
        if code in table:
            out.append(f"\t\t{code}: {q(table[code])},\n")
    out.append("\t},\n")
out.append("}\n\n")
out.append("// glyphNames maps Adobe glyph names to Unicode text.\nvar glyphNames = map[string]string{\n")
for k, v in glyphname2unicode.items():
    out.append(f"\t{q(k)}: {q(v)},\n")
out.append("}\n\n")
out.append("// std14Metrics are the AFM metrics of the standard fonts: ascent, descent and widths keyed by character.\n")
out.append("var std14Metrics = map[string]fontMetrics{\n")
for name, (desc, widths) in FONT_METRICS.items():
    out.append(f"\t{q(name)}: {{Ascent: {desc.get('Ascent', 0)}, Descent: {desc.get('Descent', 0)}, Widths: map[string]float64{{\n")
    for k, w in widths.items():
        out.append(f"\t\t{q(k)}: {w},\n")
    out.append("\t}},\n")
out.append("}\n")
open(sys.argv[1], "w").write("".join(out))
print("ok")
